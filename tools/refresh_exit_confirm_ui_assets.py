def write_new(path, data):
    require(path.parent == STAGE and path.name in {
        'ui_embedding_preflight.json', 'ui_embedding_result.json', 'UiPopupAssets.generated.h.pending', 'prepared.json.pending'},
        'Unapproved stage output')
    ordinary(STAGE, directory=True)
    require(not path.exists(), 'Stage output already exists: ' + str(path))
    with path.open('xb') as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())
    require(path.read_bytes() == data, 'Staged output readback differs')


def apply(preflight_sha, baseline_path, baseline_sha):
    require(not RESULT_PATH.exists(), 'Embedding result already exists')
    preflight = read_json(PREFLIGHT_PATH, 2 * 1024 * 1024)
    require(artifact(PREFLIGHT_PATH)['sha256'] == preflight_sha and
            preflight['status'] == 'PASS_FILE_ONLY_UI_EMBEDDING_PREFLIGHT_NOT_APPLIED', 'Unreviewed preflight')
    baseline_path = ordinary(Path(baseline_path))
    require(baseline_path.parent == STAGE and baseline_path.suffix == '.json' and
            artifact(baseline_path)['sha256'] == baseline_sha, 'Unreviewed storage baseline')
    baseline = read_json(baseline_path, 2 * 1024 * 1024)
    require(type(baseline) is dict and bool(baseline), 'Empty storage baseline')
    header, prepared, report, inputs = prepare()
    require(report == preflight, 'Source or generated output differs from reviewed preflight')
    header_stage, prepared_stage = STAGE / 'UiPopupAssets.generated.h.pending', STAGE / 'prepared.json.pending'
    write_new(header_stage, header)
    write_new(prepared_stage, prepared)
    inputs.unchanged()
    # Only the two approved, single-link derived files are replaced. The old
    # bytes already exist in their separately verified immutable recovery refs.
    os.replace(header_stage, HEADER_PATH)
    try:
        os.replace(prepared_stage, PREPARED_PATH)
    except OSError:
        require(artifact(HEADER_PATH)['sha256'] == report['outputs_expected']['header']['sha256'],
                'Header changed during failed pair publication; recovery references retained')
        write_new(header_stage, Path(report['header_recovery_ref']['path']).read_bytes())
        os.replace(header_stage, HEADER_PATH)
        raise
    header_after, prepared_after = artifact(HEADER_PATH), artifact(PREPARED_PATH)
    require(all(header_after[key] == report['outputs_expected']['header'][key] for key in ('path', 'bytes', 'sha256')) and
            all(prepared_after[key] == report['outputs_expected']['prepared'][key] for key in ('path', 'bytes', 'sha256')) and
            header_after['links'] == prepared_after['links'] == 1, 'Applied output identity differs')
    preserved = {key: artifact(report[key]['path']) for key in ('header_recovery_ref', 'prepared_recovery_ref')}
    require(all(preserved[key]['sha256'] == report[key]['sha256'] for key in preserved), 'Immutable recovery changed')
    remaining_inputs = [row for row in report['source_inputs_before']
                        if row['path'] not in (str(HEADER_PATH), str(PREPARED_PATH))]
    for row in remaining_inputs:
        require(artifact(row['path']) == row, 'Non-output input changed during application: ' + row['path'])
    report.update(status='PASS_FILE_ONLY_UI_ASSETS_EMBEDDED_NOT_HOST_LINKED_OR_EXECUTED',
                  reviewed_preflight=artifact(PREFLIGHT_PATH), storage_baseline=artifact(baseline_path),
                  current_header=header_after, current_prepared=prepared_after,
                  generated_header=header_after, prepared_report=prepared_after,
                  source_inputs_after=remaining_inputs, recovery_after=preserved,
                  pending_output_files_remaining=False,
                  logical_output_delta_bytes=header_after['bytes'] + prepared_after['bytes'] -
                      report['baseline_header']['bytes'] - report['baseline_prepared']['bytes'])
    require(not header_stage.exists() and not prepared_stage.exists(), 'A duplicate staged output remains')
    write_new(RESULT_PATH, json_bytes(report))
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--preflight-sha256')
    parser.add_argument('--storage-baseline')
    parser.add_argument('--storage-baseline-sha256')
    args = parser.parse_args()
    if args.apply:
        require(all((args.preflight_sha256, args.storage_baseline, args.storage_baseline_sha256)),
                'Apply needs the reviewed preflight and storage-baseline SHA')
        report = apply(args.preflight_sha256, args.storage_baseline, args.storage_baseline_sha256)
        output = RESULT_PATH
    else:
        require(not any((args.preflight_sha256, args.storage_baseline, args.storage_baseline_sha256)),
                'Review hashes are only used with --apply')
        _, _, report, _ = prepare()
        write_new(PREFLIGHT_PATH, json_bytes(report))
        output = PREFLIGHT_PATH
    print(json.dumps({'status': report['status'], 'report': str(output), 'payloads': report['new_catalog_payload_count'],
                      'layouts': report['new_layout_count'], 'native_code_executed': False}))


if __name__ == '__main__':
    main()
