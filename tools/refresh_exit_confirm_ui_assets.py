def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def ordinary(path, *, directory=False):
    path = Path(path).absolute()
    require(path.resolve(strict=True) == path, 'Resolved path differs: ' + str(path))
    for part in (path, *path.parents):
        info = part.lstat()
        require(not getattr(info, 'st_file_attributes', 0) & 0x400 and
                not stat.S_ISLNK(info.st_mode), 'Reparse/symlink path: ' + str(part))
    info = path.stat()
    require(stat.S_ISDIR(info.st_mode) if directory else stat.S_ISREG(info.st_mode),
            'Unexpected input type: ' + str(path))
    return path


def artifact(path):
    path = ordinary(path)
    info = path.stat()
    with path.open('rb') as stream:
        digest = hashlib.file_digest(stream, 'sha256').hexdigest()
    after = path.stat()
    require((info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns) ==
            (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns),
            'Input changed while hashing: ' + str(path))
    return {'path': str(path), 'bytes': info.st_size, 'sha256': digest,
            'file_identity': [info.st_dev, info.st_ino], 'mtime_ns': info.st_mtime_ns,
            'links': info.st_nlink}


def simple_artifact(path):
    row = artifact(path)
    return {key: row[key] for key in ('path', 'sha256')}


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + '\n').encode('utf-8')


def read_json(path, bound):
    ordinary(path)
    require(path.stat().st_size <= bound, 'JSON input exceeds bound: ' + str(path))
    return json.loads(path.read_text(encoding='utf-8'))


class FileOnlyGuard:
    """Reject native, extraction and copy entrypoints while calling real APIs."""
    def __init__(self, preparer):
        self.preparer = preparer
        self.stack = ExitStack()
        self.rejected_calls = []
        self.existing_mkdir_noops = set()

    def reject(self, label):
        def blocked(*args, **kwargs):
            self.rejected_calls.append(label)
            raise RuntimeError('Forbidden in file-only UI preparation: ' + label)
        return blocked

    def __enter__(self):
        for owner, names in (
            (subprocess, ('Popen', 'run', 'call', 'check_call', 'check_output', 'getoutput', 'getstatusoutput')),
            (os, ('system', 'startfile', 'spawnl', 'spawnle', 'spawnlp', 'spawnlpe',
                  'spawnv', 'spawnve', 'spawnvp', 'spawnvpe', 'execv', 'execve', 'execvp', 'execvpe')),
            (ctypes, ('CDLL', 'WinDLL', 'OleDLL', 'PyDLL')),
            (shutil, ('copy', 'copy2', 'copyfile', 'copytree', 'move')),
            (self.preparer, ('main', 'freeze_buy_tile_audio', 'freeze_purchase_audio_catalog', 'UiAssets', 'Fpk')),
        ):
            for name in names:
                if hasattr(owner, name):
                    self.stack.enter_context(patch.object(owner, name, self.reject(name)))
        for name in ('cdll', 'windll', 'oledll', 'pydll'):
            loader = getattr(ctypes, name, None)
            if loader is not None:
                self.stack.enter_context(patch.object(loader, 'LoadLibrary', self.reject(name + '.LoadLibrary')))
        # The real freeze_source API calls mkdir(exist_ok=True) for an existing
        # frozen parent. A verified existing directory needs no filesystem call.
        def existing_mkdir(path, *args, **kwargs):
            path = ordinary(path, directory=True)
            require(path.is_relative_to(PROJECT / 'Source/Assets/UI'), 'Unexpected freeze directory')
            self.existing_mkdir_noops.add(str(path))
        self.stack.enter_context(patch.object(Path, 'mkdir', existing_mkdir))
        for name in ('write_bytes', 'write_text', 'touch', 'unlink', 'rename', 'replace', 'symlink_to', 'hardlink_to'):
            self.stack.enter_context(patch.object(Path, name, self.reject('Path.' + name)))
        return self

    def __exit__(self, *details):
        return self.stack.__exit__(*details)


class Inputs:
    def __init__(self):
        self.rows = {}

    def verify(self, row, *, path=None, exact_identity=False):
        require(type(row) is dict and re.fullmatch('[0-9a-f]{64}', row.get('sha256', '')),
                'Invalid input artifact')
        selected = Path(path or row['path']).absolute()
        require(selected.is_relative_to(PROJECT) or selected.is_relative_to(self.game),
                'Artifact escaped project/game: ' + str(selected))
        key = str(selected).casefold()
        current = artifact(selected) if key not in self.rows else self.rows[key]
        require(current['sha256'] == row['sha256'] and
                ('bytes' not in row or current['bytes'] == row['bytes']),
                'Input identity differs: ' + str(selected))
        if exact_identity:
            require(current['file_identity'] == row['file_identity'] and
                    current['mtime_ns'] == row['mtime_ns'] and
                    ('links' not in row or current['links'] == row['links']),
                    'Mutable baseline metadata differs: ' + str(selected))
        self.rows[key] = current
        return current

    def unchanged(self):
        for row in self.rows.values():
            require(artifact(row['path']) == row, 'Verified input changed: ' + row['path'])


def parse_text_arrays(data, preparer):
    """Decode only the canonical generated char-array grammar, never C/C++."""
    text = data.decode('ascii')
    require(text.startswith(PREFIX), 'Unexpected generated header prefix')
    position = len(PREFIX)
    arrays = []
    names = set()
    pattern = re.compile(r'static const char ([A-Za-z][A-Za-z0-9_]*)\[\]=\n((?:"(?:\\x[0-9a-f]{2})*"\n?)+);\n')
    while text.startswith('static const char ', position):
        match = pattern.match(text, position)
        require(match is not None, 'Noncanonical generated text array')
        name, literals = match.groups()
        require(name not in names, 'Duplicate text array: ' + name)
        raw = bytes.fromhex(''.join(re.findall(r'\\x([0-9a-f]{2})', literals)))
        canonical = 'static const char ' + name + '[]=\n' + preparer.cpp_literal(raw) + ';\n'
        require(match.group(0) == canonical and b'\0' not in raw, 'Noncanonical or NUL text payload: ' + name)
        arrays.append((name, raw))
        names.add(name)
        position = match.end()
    require(arrays, 'No generated text arrays')
    return arrays, text[position:]


def scene_bytes(sources):
    raw = sources['host_ui_runtime']
    combined = raw + b'\n' + sources['host_ui_input_addendum']
    for key, _, guard in HOST_LUA[2:8]:
        require(guard.encode('ascii') in raw, 'Scene addendum guard missing: ' + guard)
        combined += b'\nif ' + guard.encode('ascii') + b' then\n' + sources[key] + b'\nend\n'
    return combined


def render_header(texts, audio, preparer):
    header = [PREFIX.rstrip('\n')]
    for name, data in texts:
        header.append('static const char ' + name + '[]=\n' + preparer.cpp_literal(data) + ';')
    for symbol, wav, volume, policy in audio:
        header.extend(preparer.cpp_byte_array(symbol + 'Wave', wav))
        channel = volume * 0xffff // 100
        header.extend([
            f'static const unsigned int {symbol}VolumePercent={volume}u;',
            f'static const unsigned int {symbol}WaveOutVolume=0x{channel:04x}{channel:04x}u;',
            f"static const unsigned int {symbol}MaxActive={policy['iDontPlayMoreThan'] or 0}u;",
            f"static const bool {symbol}DontTriggerDuplicates={'true' if policy['bDontTriggerDuplicates'] else 'false'};",
        ])
    header.append('static const Script scripts[]={')
    header.extend('{"' + name + '",' + name + ',sizeof(' + name + ')-1},' for name, _ in texts)
    header.extend(['};', '} }', ''])
    return '\n'.join(header).encode('ascii')


def nested_objects(value):
    if type(value) is dict:
        yield value
        for child in value.values():
            yield from nested_objects(child)
    elif type(value) is list:
        for child in value:
            yield from nested_objects(child)


def donor_source(relative, frozen, inputs, expected=None):
    candidates = [frozen / 'project' / relative, frozen / 'include_roots/project' / relative]
    matches = [path for path in candidates if path.is_file()]
    require(matches, 'Prior frozen source is missing: ' + relative)
    row = artifact(matches[0])
    if expected is not None:
        require(row['sha256'] == expected, 'Prior frozen source identity differs: ' + relative)
    inputs.verify(row)
    return matches[0]


def verify_prior_producer(source_manifest, prior_builder, inputs):
    """Use the already retained, exact small pre-change producer backup."""
    inputs.verify(source_manifest['before'])
    previous = read_json(Path(source_manifest['before']['path']), 1024 * 1024)
    rows = [row for row in previous['sources'] if row['path'] == prior_builder['path']]
    require(len(rows) == 1 and rows[0]['sha256'] == prior_builder['sha256'],
            'Prior producer backup is not bound to the prior preparation')
    row = rows[0]
    require(row['bytes'] <= 256 * 1024, 'Prior producer backup exceeds its bound')
    backup = Path(row['backup']['path'])
    require(backup.parent == PROJECT / 'evidence/game_menu/offline_exit/source_backups' and
            backup.name == 'tools__prepare_ui_popup_assets.py.before.gz', 'Unexpected producer backup path')
    inputs.verify(row['backup'])
    with gzip.open(backup, 'rb') as stream:
        raw = stream.read(row['bytes'] + 1)
    require(len(raw) == row['bytes'] and sha(raw) == prior_builder['sha256'],
            'Prior producer backup content differs')
    return {'compressed_input': artifact(backup), 'uncompressed_bytes': len(raw),
            'uncompressed_sha256': sha(raw), 'new_files_created': 0}


def normalize_bank(bank, font_api):
    require(type(bank) is dict and set(bank) == {'schema', 'profileId', 'glyphSets'} and
            bank['schema'] == font_api.BANK_SCHEMA and type(bank['glyphSets']) is dict,
            'Invalid shared font bank')
    result = deepcopy(bank)
    result['glyphSets'] = {key: font_api.integer_glyph_map(value)
                           for key, value in bank['glyphSets'].items()}
    return result


def payload_identities(texts):
    return [{'index': index, 'name': name, 'bytes': len(raw), 'sha256': sha(raw)}
            for index, (name, raw) in enumerate(texts)]


