"""Static, non-executing probe of the retail Civ V DX11 terrain-blend and fog-of-war renderer structure.

The EXE is parsed as data (pefile) and disassembled (capstone); nothing is loaded or executed.
usage: python -I retail_renderer_probe.py CivilizationV_DX11.exe OUT.json
"""
import collections, hashlib, json, re, struct, sys
import capstone, pefile
from capstone import Cs, CS_ARCH_X86, CS_MODE_32

EXPECTED_SHA256 = 'b7c8977ebab33ba6c1abf65d63fa310f8d096341465e0fc419f1b4da0fcd8818'
exe, out = sys.argv[1], sys.argv[2]
raw = open(exe, 'rb').read()
sha = hashlib.sha256(raw).hexdigest()
if sha != EXPECTED_SHA256:
    raise SystemExit('Retail EXE differs from the analysed build: ' + sha)
pe = pefile.PE(data=raw)
base = pe.OPTIONAL_HEADER.ImageBase
img = pe.get_memory_mapped_image()
md = Cs(CS_ARCH_X86, CS_MODE_32)


def u32(va):
    return struct.unpack('<I', img[va - base:va - base + 4])[0]


def cstr(va):
    o = va - base
    return img[o:img.index(b'\0', o)].decode('latin1')


def is_name(va):
    return 0xa00000 <= va < 0xb00000


def require(condition, message):
    if not condition:
        raise SystemExit('Pinned retail evidence no longer matches: ' + message)


def file_va(offset):
    return pe.get_rva_from_offset(offset) + base


report = dict(schema='zerosis.world_terrain_original.retail_renderer_probe.v1',
              exe=dict(name='CivilizationV_DX11.exe', bytes=len(raw), sha256=sha),
              tool=dict(pefile=pefile.__version__, capstone=capstone.__version__), executed=False,
              method='PE parse, pinned data-table reads and linear x86 disassembly of pinned code; no code was loaded or run.')

# 1. Autogenerated shader registry (.\shaderautogen\ShaderDefDX11.cpp): (name, id) pairs and per-id binding tables.
NAMES, BINDINGS = 0xc9e890, 0xc9e718
require(raw.count(b'.\\shaderautogen\\ShaderDefDX11.cpp') >= 1, 'autogen shader definition source name')
shaders = []
for ident in range(0x5e):
    name_va, value = u32(NAMES + ident * 8), u32(NAMES + ident * 8 + 4)
    require(value == ident and is_name(name_va), 'shader registry pair %d' % ident)
    table = u32(BINDINGS + ident * 4)
    static = 0xc90000 <= table < 0xca0000
    bindings = []
    if static:
        for slot in range(16):  # tables are 0x100 bytes apart: 16 slots of 16 bytes
            entry = u32(table + slot * 16)
            if entry and is_name(entry):
                bindings.append(cstr(entry))
    shaders.append(dict(id=ident, name=cstr(name_va), binding_table=f'{table:08x}',
                        binding_table_kind='static rdata' if static else 'runtime-filled (.bss)', bindings=bindings))
by_name = {row['name']: row for row in shaders}
expected = {'TerrainShader': 0x49, 'NormalCalculate': 0x4a, 'CacheBake': 0x4b, 'TerrainShaderScreen': 0x4c,
            'CompositeShader': 0x4d, 'TerrainDecalShader': 0x4e, 'FOWCell': 0x32, 'FOWParticleShader': 0x33,
            'FOWDrawMask': 0x34, 'FOWBaseLayer': 0x35, 'ForestShader': 0x2c, 'GridShader': 0x3a, 'RiverShader': 0x45,
            'WaterShader': 0x5b, 'WaveShader': 0x5c}
for name, ident in expected.items():
    require(by_name[name]['id'] == ident, 'shader id ' + name)
for name in ('TerrainShader', 'NormalCalculate', 'CacheBake', 'TerrainShaderScreen', 'CompositeShader', 'TerrainDecalShader'):
    require(by_name[name]['binding_table_kind'].startswith('runtime'), name + ' bindings are filled at runtime')
require(by_name['FOWParticleShader']['bindings'] == ['PartTexture', 'FOWMask'], 'FOWParticleShader bindings')
require(by_name['FOWDrawMask']['bindings'] == ['FOWBaseLayerTexture', 'FOWBaseMask'] ==
        by_name['FOWBaseLayer']['bindings'], 'FOWDrawMask/FOWBaseLayer bindings')
require(by_name['ForestShader']['bindings'][-4:] == ['ColorCorrection', 'FOWMask', 'FOWBaseLayer', 'TransFOWColor'],
        'forest shader consumes the fog-of-war mask and base layer')
require('FOWMask' in by_name['WaterShader']['bindings'] and 'TransFOWColor' in by_name['WaterShader']['bindings'],
        'water shader consumes the fog-of-war mask')
report['shader_registry'] = dict(names_table=f'{NAMES:08x}', bindings_table=f'{BINDINGS:08x}', stride_bytes=16,
                                 shaders=shaders)

# 2. Embedded DXBC bytecode: count, stages, and that reflection (RDEF) is stripped.
stages = collections.Counter()
chunk_sets = collections.Counter()
for match in re.finditer(b'DXBC', raw):
    offset = match.start()
    if offset + 32 > len(raw):
        continue
    size, count = struct.unpack_from('<II', raw, offset + 24)
    if not (32 < size < 2_000_000 and 0 < count < 16):
        continue
    blob = raw[offset:offset + size]
    chunks = {}
    for chunk_offset in struct.unpack_from('<%dI' % count, blob, 32):
        chunks[blob[chunk_offset:chunk_offset + 4].decode('latin1')] = chunk_offset + 8
    code = chunks.get('SHDR', chunks.get('SHEX'))
    if code is None:
        continue
    stages[{0: 'PS', 1: 'VS', 2: 'GS', 3: 'HS', 4: 'DS', 5: 'CS'}[struct.unpack_from('<I', blob, code)[0] >> 16]] += 1
    chunk_sets[','.join(sorted(chunks))] += 1
require(sum(stages.values()) == 1417 and stages['HS'] == 2 and stages['DS'] == 1, 'embedded DXBC inventory')
require(not any('RDEF' in key for key in chunk_sets), 'embedded DXBC has no RDEF reflection')
report['embedded_dxbc'] = dict(blobs=sum(stages.values()), stages=dict(stages), chunk_sets=dict(chunk_sets),
                               reflection='stripped: no RDEF chunk, so texture/constant names are not in the bytecode')

# 3. Texture category names used by the renderer (debug/budget categories).
categories_va = 0xb94140
categories = [cstr(u32(categories_va + 4 * k)) for k in range(-3, 6)]
require(categories[3:7] == ['Terrain Piece Heightmap', 'Terrain Piece Blend/ID', 'Terrain Decal Diffuse', 'Terrain Decal Height'],
        'terrain texture categories')
report['texture_categories'] = dict(table=f'{categories_va - 12:08x}', names=categories)

# 4. Source-file and asset path strings that tie the systems to their data.
def strings_near(needle, before=200, after=400):
    index = raw.find(needle)
    require(index >= 0, needle.decode('latin1'))
    return [s.decode('latin1') for s in re.findall(rb'[ -~]{4,}', raw[max(0, index - before):index + after])]


evidence_strings = {
    'terrain_blend': strings_near(b'Resource\\Common\\TerrainPiecesLibrary.fxsb', 200, 200),
    'terrain_system': strings_near(b'assets\\terrain\\TerrainTextures\\TerrainDef.csv', 80, 160),
    'fluid_fow': strings_near(b'.\\App\\Graphics\\FluidFOW.cpp', 40, 200),
    'distance_fog': strings_near(b'assets/DistanceFog/', 20, 120),
}
require(any('cvTerrainBlend.cpp' in s for s in evidence_strings['terrain_blend']), 'pieces library loaded by cvTerrainBlend.cpp')
require(any('FogCloudTile_dif_01.dds' in s for s in evidence_strings['fluid_fow']), 'fluid fog cloud tiles')
require(any('FogColor.csv' in s for s in evidence_strings['distance_fog']) and
        any('FogRamp.dds' in s for s in evidence_strings['distance_fog']), 'distance fog inputs')
report['source_strings'] = evidence_strings

# 5. FluidFOW resource setup: three cloud tiles, flow field, fog diffuse and four 0x80-byte descriptor allocations
#    (0x8c69b0 zero-fills a pooled descriptor; what each describes is not established here).
start, stop = 0x44ae80, 0x44b260
rows = [(i.address, i.mnemonic, i.op_str) for i in md.disasm(img[start - base:stop - base], start)]
pushes = [cstr(int(op, 16)) for _, mn, op in rows if mn == 'push' and op.startswith('0x') and is_name(int(op, 16))]
descriptors = sum(1 for _, mn, op in rows if mn == 'call' and op == '0x8c69b0')
require(pushes[:3] == ['FogCloudTile_dif_02.dds', 'FogCloudTile_dif_03.dds', 'FogCloudTile_dif_01.dds'] and
        'flowfield.dds' in pushes and 'FX_Fog_dif.dds' in pushes and descriptors == 4, 'FluidFOW setup')
helper = [f'{i.mnemonic} {i.op_str}' for i in md.disasm(img[0x8c69b0 - base:0x8c69f0 - base], 0x8c69b0)]
require('push 0x80' in helper and 'call 0x926842' in helper and helper[-1] == 'ret 0xc', 'pooled 0x80-byte descriptor helper')
report['fluid_fow_setup'] = dict(descriptor_helper=helper, function_range=[f'{start:08x}', f'{stop:08x}'], pushed_names=pushes,
                                 pooled_descriptor_allocations_0x8c69b0=descriptors)

# 6. Shader descriptor constructor for TerrainShader: id 0x49 with runtime registration.
ctor = [f'{i.mnemonic} {i.op_str}' for i in md.disasm(img[0x6f60b3 - base:0x6f60c7 - base], 0x6f60b3)]
require(ctor[:2] == ['mov dword ptr [esi + 0xc], 0xa93550', 'mov dword ptr [esi], 0x49'], 'TerrainShader descriptor')
report['terrain_shader_descriptor'] = dict(listing=ctor, name=cstr(0xa93550))

report['interpretation'] = dict(
    proven=['Terrain blending is a dedicated system (cvTerrainBlend.cpp) fed by Resource/Common/TerrainPiecesLibrary.fxsb '
            'with per-piece heightmap and blend/ID textures, not a per-hex flat texture.',
            'Terrain, normal, cache-bake, screen, composite and decal shaders exist as separate registered shaders whose '
            'texture bindings are filled at runtime.',
            'Fog of war has its own mask/base-layer/particle shaders, and forest/water/building-family shaders read FOWMask, '
            'FOWBaseLayer and TransFOWColor/FOWColorKey.',
            'Animated fog clouds (FluidFOW) load three 1024px cloud tiles, a flow field and a fog diffuse.',
            'Distance fog uses FogColor.csv and FogRamp.dds.'],
    not_proven=['The exact blend arithmetic (height blend, BaseDominance use, hexgridid.dds/tf_blend.dds roles).',
                'The TerrainPiecesLibrary.fxsb record format.',
                'Which embedded DXBC belongs to which registered shader (reflection is stripped).',
                'Whether the 2 hull + 1 domain shaders are the terrain tessellation path.',
                'What the four pooled descriptors allocated in the FluidFOW setup describe.'])
with open(out, 'w', encoding='utf8', newline='\n') as stream:
    json.dump(report, stream, indent=1)
    stream.write('\n')
print(json.dumps(dict(status='PASS_RETAIL_RENDERER_STATIC_PROBE', exe_sha256=sha, shaders=len(shaders),
                      dxbc=sum(stages.values()), out=out)))
